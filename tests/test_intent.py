import numpy as np
import sys
import os
# 路径黑魔法
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.core.intent import IntentInference

def test_intent_logic():
    intent = IntentInference(dist_thresh=0.1, vel_thresh=0.1)
    
    # Case 1: 离得远 (1.0m)，速度快 (1.0m/s) -> 应该是自由模式 (alpha -> 0)
    alpha_free = intent.compute_alpha(p_err=1.0, v_hand=1.0)
    print(f"Alpha Free: {alpha_free}")
    assert alpha_free < 0.1, "Error: Should be Free Mode!"

    # Case 2: 离得近 (0.01m)，速度慢 (0.01m/s) -> 应该是精密模式 (alpha -> 1)
    alpha_fine = intent.compute_alpha(p_err=0.01, v_hand=0.01)
    print(f"Alpha Fine: {alpha_fine}")
    assert alpha_fine > 0.9, "Error: Should be Fine Mode!"

    # Case 3: 离得近但速度快 -> 不应该完全吸附 (alpha 应该居中或偏小)
    alpha_mixed = intent.compute_alpha(p_err=0.01, v_hand=1.0)
    assert alpha_mixed < 0.5, "Error: Fast movement should prevent sticking!"












































































































































































































































































